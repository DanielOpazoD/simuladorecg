/** Production-only worker -> model audit -> visible HR quality, without source imports. */
import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
const url=process.env.ECG_TEST_URL||'http://127.0.0.1:5173/';
const out=path.resolve(process.env.ECG_EVIDENCE_DIR||'.sites-runtime/hr-quality-browser');
await mkdir(out,{recursive:true});
const response=await fetch(new URL('build-info.json',url));assert.equal(response.status,200);
const identity=await response.json();
assert.deepEqual(identity,JSON.parse(await readFile('dist/build-info.json')));
assert.equal(identity.dirty,false);
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[],warnings=[],checks=[],requests=[];
page.on('pageerror',e=>errors.push(e.message));page.on('request',r=>requests.push(r.url()));
page.on('console',m=>{if(m.type()==='error')errors.push(m.text());if(m.type()==='warning')warnings.push(m.text());});
const ready=()=>page.locator('#signal-loading').waitFor({state:'hidden'});
try {
 await page.goto(url);await ready();
 assert.match(await page.title(),/ECG/);assert.equal(new URL(page.url()).origin,new URL(url).origin);
 assert.equal(await page.locator('vite-error-overlay').count(),0);
 assert.ok(await page.locator('#ecg').evaluate(c=>c.width>0&&c.height>0));
 checks.push('production identity, nonblank, no overlay');
 await page.locator('[data-preset="pvc"]').click();await ready();
 await page.locator('[data-action="export"]').click();
 const pending=page.waitForEvent('download');await page.locator('[data-action="json"]').click();
 const file=path.join(out,'native-pvc.json');await(await pending).saveAs(file);
 await page.locator('#dialog').evaluate(d=>d.close());
 const ecg=JSON.parse(await readFile(file));ecg.filter='off';ecg.artifacts.muscle=.1;
 await page.locator('#file-input').setInputFiles({name:'native-noisy-pvc.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(ecg))});
 await page.waitForFunction(()=>document.querySelector('#metrics .main-metric')?.getAttribute('title')?.includes('sensible al umbral'));
 await ready();
 const metric=page.locator('#metrics .main-metric');
 assert.match(await metric.innerText(),/Revisar/);
 assert.doesNotMatch(await metric.locator('strong').innerText(),/[—–]/);
 checks.push('real worker preserves HR and marks review for native noisy PVC');
 await metric.click();
 assert.match(await page.locator('#dialog .evidence-notes').innerText(),/sensible al umbral/);
 await page.screenshot({path:path.join(out,'hr-quality-review.png')});
 await page.locator('#dialog').evaluate(d=>d.close());
 checks.push('quality reason visible in measurements dialog');
 await page.setViewportSize({width:390,height:844});
 await metric.scrollIntoViewIfNeeded();assert.match(await metric.innerText(),/Revisar/);
 await page.screenshot({path:path.join(out,'hr-quality-mobile.png')});
 await page.setViewportSize({width:1440,height:1000});
 await page.locator('[data-preset="pvc"]').click();await ready();
 assert.doesNotMatch(await metric.getAttribute('title'),/sensible al umbral/);
 checks.push('mobile-sized badge and clean-preset recovery');
 const paths=requests.filter(u=>new URL(u).origin===new URL(url).origin).map(u=>new URL(u).pathname);
 assert.ok(paths.some(p=>/^\/assets\/.*\.js$/.test(p)));
 assert.ok(!paths.some(p=>p.startsWith('/src/')||p.includes('@vite/client')));
 assert.deepEqual(errors,[]);assert.deepEqual(warnings,[]);
 checks.push('compiled assets only and healthy console');
 await writeFile(path.join(out,'browser-results.json'),JSON.stringify({identity,url,checks,errors,warnings,browser:await browser.version(),viewports:[[1440,1000],[390,844]],physicalDeviceTest:false},null,2));
 console.log(JSON.stringify({passed:checks.length,errors,warnings}));
} catch(e) {
 await page.screenshot({path:path.join(out,'failure.png'),fullPage:true}).catch(()=>{});
 await writeFile(path.join(out,'failure.json'),JSON.stringify({error:String(e),checks,errors,warnings},null,2));throw e;
} finally {await browser.close();}
